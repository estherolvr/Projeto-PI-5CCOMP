import { test, expect, api, profile, evidence } from './fixtures'

test('ADJ-003 @read ASA abre perfil acadêmico real e histórico após recarregar', async ({ session }, info) => {
  await session('student')
  const student = profile('student')
  const page = await session('asa')
  const data = await api(page, `/api/students/${student.id}`)
  expect(data.status).toBe(200)
  await page.goto('/asa/alunos')
  await page.getByPlaceholder('Buscar por nome, RA ou curso...').fill(student.ra)
  await page.getByRole('button', { name: `Ver perfil acadêmico de ${student.name}`, exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Perfil acadêmico do aluno' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText(data.data.course, { exact: true })).toBeVisible()
  await expect(dialog.getByText(`RA: ${data.data.ra}`, { exact: true })).toBeVisible()
  await expect(dialog.getByText(data.data.email, { exact: true })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: `Histórico de chamados (${data.data.tickets.length})`, exact: true })).toBeVisible()
  await page.reload()
  await page.getByPlaceholder('Buscar por nome, RA ou curso...').fill(student.ra)
  await page.getByRole('button', { name: `Ver perfil acadêmico de ${student.name}`, exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Perfil acadêmico do aluno' })
  await expect(dialog.getByText(data.data.course, { exact: true })).toBeVisible()
  await evidence(page, info, 'asa-academic-profile')
})

test('ADJ-004 @read Admin consulta descrição persistida do agendamento', async ({ session }, info) => {
  await session('student')
  const page = await session('admin')
  const listed = await api(page, `/api/appointments?studentId=${encodeURIComponent(profile('student').id)}`)
  expect(listed.status).toBe(200)
  const record = listed.data.find((appointment: any) => appointment.notes?.trim())
  if (!record) throw new Error('PRECONDITION: no appointment with description for the authorized test student; no real record was modified')
  await page.goto('/admin/agendamentos')
  await page.getByLabel('Buscar agendamento').fill(record.protocol)
  await page.getByRole('button', { name: `Ver detalhes do agendamento ${record.protocol}`, exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Detalhes do agendamento' })).toBeVisible()
  await expect(page.getByTestId('appointment-description')).toHaveText(record.notes)
  await page.reload()
  await page.getByLabel('Buscar agendamento').fill(record.protocol)
  await page.getByRole('button', { name: `Ver detalhes do agendamento ${record.protocol}`, exact: true }).click()
  const fresh = await api(page, `/api/appointments/${record.id}`)
  expect(fresh.status).toBe(200)
  await expect(page.getByTestId('appointment-description')).toHaveText(fresh.data.notes)
  await evidence(page, info, 'admin-appointment-description')
})

test('ADJ-005 @read menus removidos e permissões separadas por perfil', async ({ session }, info) => {
  const admin = await session('admin')
  await expect(admin.getByRole('link', { name: /^Automações?$|^Regras$/i })).toHaveCount(0)
  await admin.goto('/admin/automacoes')
  await expect(admin).not.toHaveURL(/\/admin\/automacoes$/)
  await expect(admin.getByRole('heading', { name: 'Automações e Regras', exact: true })).toHaveCount(0)
  const student = await session('student')
  await student.goto('/admin/sla')
  await expect(student).toHaveURL(/\/aluno$/)
  expect((await api(student, '/api/admin/sla-monitor')).status).toBe(403)
  const asa = await session('asa')
  expect((await api(asa, '/api/admin/sla-rules/nonexistent-qa-rule', 'PUT', {})).status).toBe(403)
  await asa.goto('/admin')
  await expect(asa).toHaveURL(/\/asa$/)
  await evidence(student, info, 'student-role-boundary')
})

test('ADJ-006 @read ASA consulta monitor de SLA e sino de notificações', async ({ session }, info) => {
  const page = await session('asa')
  const monitor = await api(page, '/api/admin/sla-monitor')
  expect(monitor.status).toBe(200)
  await page.goto('/asa/sla')
  await expect(page.locator('h1')).toContainText(/SLA/i)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Notificações', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Notificações recentes' })).toBeVisible()
  expect((await api(page, '/api/notifications')).status).toBe(200)
  await page.goto('/asa/notificacoes')
  await expect(page.getByRole('heading', { name: /Notifica/i }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Atualizar', exact: true })).toBeVisible()
  await evidence(page, info, 'asa-notifications')
})
