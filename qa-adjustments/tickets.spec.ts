import { test, expect, api, allowWrites, downloadMatches, evidence } from './fixtures'

test('ADJ-001 @write Aluno anexa chamado; ASA responde, resolve e consulta histórico; notificações persistem', async ({ session }, info) => {
  allowWrites()
  const student = await session('student')
  const asa = await session('asa')
  const marker = `QA-AJUSTES-${Date.now()}`
  const filename = `${marker.toLowerCase()}.png`
  const bytes = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64')
  await student.goto('/aluno/chamados/novo')
  await student.getByLabel('Assunto', { exact: true }).fill(marker)
  await student.getByLabel('Categoria', { exact: true }).selectOption({ label: 'Acadêmico' })
  await student.getByLabel('Descrição Detalhada', { exact: true }).fill('Registro isolado de teste autorizado para validar anexos, histórico e notificações. Não representa solicitação real.')
  await student.locator('input[type=file]').setInputFiles({ name: filename, mimeType: 'image/png', buffer: bytes })
  await student.getByRole('button', { name: 'Continuar', exact: true }).click()
  const createdPromise = student.waitForResponse(response => new URL(response.url()).pathname.replace(/\/$/, '') === '/api/tickets' && response.request().method() === 'POST')
  await student.getByRole('button', { name: 'Confirmar e abrir chamado', exact: true }).click()
  const created = await createdPromise
  expect(created.status()).toBe(201)
  const ticket = await created.json()
  await info.attach('controlled-record', { body: Buffer.from(JSON.stringify({ kind: 'test-ticket', id: ticket.id, number: ticket.number, marker })), contentType: 'application/json' })
  await student.getByRole('button', { name: 'Acompanhar chamado', exact: true }).click()
  await expect(student).toHaveURL(new RegExp(`/aluno/chamados/${ticket.id}$`))
  await student.reload()
  await downloadMatches(student, student.getByRole('button', { name: new RegExp(filename) }), bytes)
  const stored = await api(student, `/api/tickets/${ticket.id}`)
  expect(stored.status).toBe(200)
  const attachments = stored.data.messages.flatMap((message: any) => message.attachments || [])
  expect(attachments.length).toBe(1)
  expect(attachments[0].name).toBe(filename)
  const unauthenticated = await student.evaluate(async ({ ticketId, attachmentId }) => (await fetch(`/api/tickets/${ticketId}/attachments/${attachmentId}/download`)).status, { ticketId: ticket.id, attachmentId: attachments[0].id })
  expect(unauthenticated).toBe(401)

  await asa.goto('/asa/notificacoes')
  const initialFeed = await api(asa, '/api/notifications')
  const createdNotification = initialFeed.data.find((item: any) => item.id === `ticket-created:${ticket.id}`)
  expect(Boolean(createdNotification), 'ASA deve receber o novo chamado real').toBe(true)
  expect(createdNotification.read).toBe(false)
  const article = asa.locator('article').filter({ hasText: createdNotification.title }).filter({ hasText: marker })
  await article.getByRole('button', { name: 'Marcar como lida', exact: true }).click()
  await asa.reload()
  const readFeed = await api(asa, '/api/notifications')
  expect(readFeed.data.find((item: any) => item.id === createdNotification.id).read).toBe(true)

  await asa.goto(`/asa/chamados/${ticket.id}`)
  await expect(asa.getByRole('heading', { name: marker, exact: true })).toBeVisible()
  await downloadMatches(asa, asa.getByRole('button', { name: new RegExp(filename) }), bytes)
  const responseText = `Resposta de validação ${marker}. Anexo recebido corretamente.`
  await asa.getByPlaceholder('Digite sua resposta para o aluno...').fill(responseText)
  const replyPromise = asa.waitForResponse(response => new URL(response.url()).pathname === `/api/tickets/${ticket.id}/messages` && response.request().method() === 'POST')
  await asa.getByRole('button', { name: 'Enviar Resposta', exact: false }).click()
  const replied = await replyPromise
  expect(replied.status()).toBe(201)
  const reply = await replied.json()
  await student.reload()
  await expect(student.getByText(responseText, { exact: true })).toBeVisible()
  await student.getByRole('button', { name: 'Notificações', exact: true }).click()
  const popup = student.getByRole('dialog', { name: 'Notificações recentes' })
  await expect(popup).toBeVisible()
  const studentFeed = await api(student, '/api/notifications')
  const replyNotification = studentFeed.data.find((item: any) => item.id === `ticket-message:${reply.id}`)
  expect(Boolean(replyNotification), 'Aluno deve receber resposta pública da equipe').toBe(true)
  const replyArticle = popup.locator('article').filter({ hasText: replyNotification.title }).filter({ hasText: marker })
  await replyArticle.getByRole('button', { name: 'Marcar como lida', exact: true }).click()
  await student.reload()
  const persistedFeed = await api(student, '/api/notifications')
  expect(persistedFeed.data.find((item: any) => item.id === replyNotification.id).read).toBe(true)

  await asa.getByRole('button', { name: 'aberto', exact: true }).click()
  const resolvedPromise = asa.waitForResponse(response => new URL(response.url()).pathname === `/api/tickets/${ticket.id}` && response.request().method() === 'PATCH')
  await asa.getByRole('button', { name: 'resolvido', exact: true }).click()
  expect((await resolvedPromise).status()).toBe(200)
  await asa.goto('/asa/chamados')
  await asa.getByRole('button', { name: 'Histórico completo', exact: true }).click()
  await asa.getByRole('button', { name: 'Resolvidos', exact: true }).click()
  await asa.getByPlaceholder('Buscar por número (#1058), aluno, RA ou assunto...').fill(marker)
  await expect(asa.getByText(marker, { exact: true })).toBeVisible()
  await asa.reload()
  await expect(asa).toHaveURL(/view=history/)
  await asa.getByPlaceholder('Buscar por número (#1058), aluno, RA ou assunto...').fill(marker)
  await expect(asa.getByText(marker, { exact: true })).toBeVisible()
  const history = await api(asa, `/api/tickets/${ticket.id}`)
  expect(history.status).toBe(200)
  expect(history.data.status).toBe('resolvido')
  expect(history.data.messages.some((message: any) => message.id === reply.id && message.content === responseText)).toBe(true)
  await evidence(asa, info, 'asa-persisted-ticket-history')
})
